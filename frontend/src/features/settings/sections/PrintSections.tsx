const EMPTY = { code: "", name: "", address: "", phone: "", email: "", registration: "", footer_text: "" };

export function BranchesSection() {
  const qc = useQueryClient();
  const { data, isLoading } = useQuery({ queryKey: ["branches", "all"], queryFn: () => api<Branch[]>("/api/branches?all=true") });
  const [edit, setEdit] = useState<(typeof EMPTY & { id?: string }) | null>(null);
  const [busy, setBusy] = useState(false);
  const refresh = () => { qc.invalidateQueries({ queryKey: ["branches"] }); qc.invalidateQueries({ queryKey: ["me"] }); };
  const save = async () => {
    if (!edit) return;
    setBusy(true);
    try {
      const { id, code, ...rest } = edit;
      const body = Object.fromEntries(Object.entries(rest).map(([k, v]) => [k, v === "" ? null : v]));
      if (id) await api(`/api/branches/${id}`, { method: "PATCH", body }); else await api("/api/branches", { method: "POST", body: { ...body, code } });
      toast.success(id ? "Branch updated" : "Branch added"); setEdit(null); refresh();
    } catch (e) { toast.error(e instanceof ApiError ? e.message : "Could not save"); } finally { setBusy(false); }
  };
  const patch = async (b: Branch, body: object, msg: string) => {
    try { await api(`/api/branches/${b.id}`, { method: "PATCH", body }); toast.success(msg); refresh(); } catch (e) { toast.error(e instanceof ApiError ? e.message : "Failed"); }
  };
  const f = (k: keyof typeof EMPTY, label: string, cls = "") => <Field label={label} className={cls}><Input value={edit?.[k] ?? ""} disabled={k === "code" && !!edit?.id} onChange={(e) => setEdit((x) => x && { ...x, [k]: e.target.value })} /></Field>;
  return (
    <Card className="overflow-hidden">
      <div className="flex items-center justify-between border-b px-[var(--card-pad)] py-4">
        <div><h3 className="flex items-center gap-2 text-[0.95rem] font-semibold"><GitBranch className="size-4 text-primary" /> Branches</h3><p className="text-[0.8rem] text-muted-foreground">Each branch has its own day list, letterhead details and staff. Patient records are shared, so a patient can be seen at any branch.</p></div>
        <Button size="sm" onClick={() => setEdit({ ...EMPTY })}><Plus /> Add branch</Button>
      </div>
      {isLoading ? <div className="p-4"><Skeleton className="h-32" /></div> : (
        <Table>
          <THead><TR><TH>Branch</TH><TH>Contact</TH><TH>Staff</TH><TH>Status</TH><TH /></TR></THead>
          <TBody>
            {data?.map((b) => (
              <TR key={b.id}>
                <TD><div className="font-medium">{b.name}</div><div className="text-xs text-muted-foreground">{b.code}</div></TD>
                <TD className="text-xs text-muted-foreground">{[b.phone, b.email].filter(Boolean).join(" · ") || "—"}</TD>
                <TD className="num">{b.staff ?? 0}</TD>
                <TD><div className="flex gap-1">{b.is_default && <Badge tone="primary">Main</Badge>}<Badge tone={b.is_active ? "success" : "neutral"}>{b.is_active ? "Active" : "Closed"}</Badge></div></TD>
                <TD className="space-x-1 text-right">
                  <Button size="xs" variant="ghost" onClick={() => setEdit({ id: b.id, code: b.code, name: b.name, address: b.address ?? "", phone: b.phone ?? "", email: b.email ?? "", registration: b.registration ?? "", footer_text: b.footer_text ?? "" })}>Edit</Button>
                  {!b.is_default && b.is_active && <Button size="xs" variant="ghost" onClick={() => patch(b, { is_default: true }, "Now the main branch")}>Make main</Button>}
                  {!b.is_default && <Button size="xs" variant="ghost" onClick={() => patch(b, { is_active: !b.is_active }, b.is_active ? "Branch closed" : "Branch reopened")}>{b.is_active ? "Close" : "Reopen"}</Button>}
                </TD>
              </TR>
            ))}
          </TBody>
        </Table>
      )}
      <Dialog open={!!edit} onOpenChange={(o) => !o && setEdit(null)}>
        <DialogContent title={edit?.id ? "Edit branch" : "Add branch"} footer={<><Button variant="secondary" onClick={() => setEdit(null)}>Cancel</Button><Button onClick={save} loading={busy} disabled={!edit?.name || (!edit?.id && edit.code.length < 2)}>Save branch</Button></>}>
          <div className="grid gap-4 sm:grid-cols-2">
            {f("name", "Name")}{f("code", "Short code")}
            <Field label="Address" className="sm:col-span-2"><Textarea rows={2} value={edit?.address ?? ""} onChange={(e) => setEdit((x) => x && { ...x, address: e.target.value })} /></Field>
            {f("phone", "Phone")}{f("email", "Email")}{f("registration", "Registration no.", "sm:col-span-2")}{f("footer_text", "Footer line", "sm:col-span-2")}
          </div>
        </DialogContent>
      </Dialog>
    </Card>
  );
}
