/** The unsaved draft rendered by the server exactly as it will print, refreshed shortly after each change. */
function usePreview(overrides: Record<string, any> | null, branchId?: string) {
  const [url, setUrl] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const last = useRef<string | null>(null);
  const key = JSON.stringify([overrides, branchId]);
  useEffect(() => {
    if (!overrides) return;
    const t = setTimeout(async () => {
      setBusy(true);
      try {
        const res = await fetch("/api/settings/print/preview", { method: "POST", credentials: "include", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ overrides, branch_id: branchId }) });
        if (!res.ok) throw new Error((await res.json().catch(() => ({}))).detail ?? "Preview failed");
        const next = URL.createObjectURL(await res.blob());
        if (last.current) URL.revokeObjectURL(last.current);
        last.current = next; setUrl(next); setError(null);
      } catch (e) { setError(e instanceof Error ? e.message : "Preview failed"); } finally { setBusy(false); }
    }, 450);
    return () => clearTimeout(t);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [key]);
  useEffect(() => () => { if (last.current) URL.revokeObjectURL(last.current); }, []);
  return { url, error, busy };
}

